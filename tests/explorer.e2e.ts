import {test,expect} from '@playwright/test'
test.beforeEach(async({page})=>{
 await page.addInitScript(()=>localStorage.setItem('voto-atlas:hide-tutorial','1'))
 // This suite verifies account dialogs; the real WebGL hierarchy is covered in browser.e2e.
 await page.route(/\/src\/components\/BrazilMap\.tsx/,route=>route.fulfill({contentType:'application/javascript',body:'export default function Map(){ return null; }'}))
 await page.route(/https:\/\/(resultados|cdn|divulgacandcontas)\.tse\.jus\.br\//,r=>r.abort('failed'))
 await page.goto('/')
 const csv='ANO_ELEICAO;NR_TURNO;CD_CARGO;SQ_CANDIDATO;NM_URNA_CANDIDATO;NR_CANDIDATO;SG_PARTIDO;SG_UF;QT_VOTOS_NOMINAIS\n2026;1;6;250002546642;KIM KATAGUIRI;1414;MISSÃO;SP;100'
 await page.locator('input[type=file]').setInputFiles({name:'fixture_votos.csv',mimeType:'text/csv',buffer:Buffer.from(csv)})
 await expect(page.locator('.candidate-card')).toHaveCount(1)
 await page.locator('.candidate-card').click()
 await expect(page.locator('.fiche-totals')).toContainText('470.347,01')
})
test('graphs drill down through records and Escape preserves the candidacy',async({page})=>{
 await expect(page.locator('.candidate-modal details')).toHaveCount(0)
 await page.getByRole('button',{name:'Ver gráficos',exact:true}).click()
 await expect(page.locator('.account-window')).toBeVisible()
 await expect(page.locator('.candidate-modal')).toHaveAttribute('inert','')
 await page.getByRole('button',{name:'Origem do dinheiro',exact:true}).click()
 await page.locator('.account-chart-row').first().click()
 await expect(page.locator('.account-record-row').first()).toBeVisible()
 await page.locator('.account-record-row').first().click()
 await expect(page.locator('.account-description')).toBeVisible()
 await page.keyboard.press('Escape')
 await expect(page.locator('.account-record-row').first()).toBeVisible()
 await page.getByRole('button',{name:'Fechar todas as janelas e voltar à candidatura'}).click()
 await expect(page.locator('.account-overlay')).toHaveCount(0)
 await expect(page.locator('.candidate-modal')).toBeVisible()
})
test('expense details show payment sidebar and the reconciliation list',async({page})=>{
 await page.getByRole('button',{name:/Despesas e documentos/}).click()
 await page.locator('.account-chart-row').first().click()
 await page.locator('.account-record-row').first().click()
 await expect(page.locator('.account-payment-aside')).toBeVisible()
 await expect(page.locator('.account-expense-items')).toBeVisible()
 await expect(page.locator('.account-settlement [role=progressbar]')).toHaveAttribute('aria-valuenow','100')
 await page.locator('.account-payment-card').first().click()
 await expect(page.locator('.account-forward')).toContainText('Abrir despesa vinculada')
 await page.getByRole('button',{name:'Fechar todas as janelas e voltar à candidatura'}).click()
 await page.locator('.fiche-balance').click()
 await expect(page.locator('.account-record-row')).toHaveCount(1)
 await page.locator('.account-record-row').click()
 await expect(page.locator('.account-settlement')).toContainText('5.000,00')
 await expect(page.locator('.account-settlement [role=progressbar]')).toHaveAttribute('aria-valuenow','0')
 await page.getByRole('button',{name:'Fechar todas as janelas e voltar à candidatura'}).click()
 await page.getByRole('button',{name:/Bens declarados/}).click()
 await expect(page.locator('.account-record-row')).toHaveCount(7)
 for(const viewport of [{width:1440,height:900},{width:390,height:844}]){
  await page.setViewportSize(viewport)
  expect(await page.evaluate(()=>document.documentElement.scrollHeight<=innerHeight&&document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 }
})

